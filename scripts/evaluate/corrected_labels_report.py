"""
Renders docs/results_corrected_labels.md from
results/corrected_labels/comparison.json and the two passes
(scripts/evaluate/corrected_labels.py). Every number in that file comes from
here; nothing is typed by hand.
"""

from __future__ import annotations

import pandas as pd

from scripts.evaluate.label_corrections import known_diffs, load_record

MODELS = ("Cox", "RSF", "XGBoost-AFT")
RANKINGS = MODELS + ("EPSS-alone",)
LANDMARKS = ("7", "14", "30")
HORIZONS = ("30", "90", "180")
BUDGETS = ("1pct", "5pct", "10pct")
PAIRED = ("cindex", "recall_1pct", "recall_5pct", "recall_10pct")
PAIRED_NAMES = {"cindex": "ΔC-index", "recall_1pct": "ΔRecall@1%", "recall_5pct": "ΔRecall@5%",
                "recall_10pct": "ΔRecall@10%"}


def _get(d, path):
    for k in path:
        d = d[k]
    return d


def _num(x, digits, sign=False):
    if x is None or x != x:
        return "—"
    return f"{x:+.{digits}f}" if sign else f"{x:.{digits}f}"


def _cell(node, digits):
    """'0.850 (0.810–0.887)' for an estimate, '+0.100 (+0.069, +0.139)' for a
    paired difference (bold when its CI excludes zero), the value otherwise."""
    if isinstance(node, dict) and "point_diff" in node:
        s = (f"{_num(node['point_diff'], digits, True)} ({_num(node['ci_lower'], digits, True)}, "
             f"{_num(node['ci_upper'], digits, True)})")
        return f"**{s}**" if node["excludes_zero"] else s
    if isinstance(node, dict) and "point" in node:
        return f"{_num(node['point'], digits)} ({_num(node['ci_lower'], digits)}–{_num(node['ci_upper'], digits)})"
    if isinstance(node, float):
        return _num(node, digits)
    return f"{node:,}" if isinstance(node, int) else str(node)


def _point(node):
    if isinstance(node, dict):
        return node.get("point_diff", node.get("point"))
    return node


def _sig(node, null):
    lo, hi = node["ci_lower"], node["ci_upper"]
    return lo > null or hi < null


class Table:
    def __init__(self, recorded, corrected, header="Metric"):
        self.recorded, self.corrected = recorded, corrected
        self.lines = [f"| {header} | Recorded | Corrected | Δ | Boundary |", "|---|---|---|---|---|"]

    def row(self, label, path, digits=3, null=None):
        r, c = _get(self.recorded, path), _get(self.corrected, path)
        rp, cp = _point(r), _point(c)
        diff = None if rp is None or cp is None else cp - rp
        if isinstance(rp, int) and isinstance(cp, int):
            delta = f"{diff:+,}" if diff else "0"
        else:
            delta = _num(diff, digits + 1, True) if diff else "0"
        flag = ""
        if isinstance(r, dict) and "ci_lower" in r:
            null = 0.0 if "point_diff" in r else null
            if null is not None:
                rs, cs = _sig(r, null), _sig(c, null)
                if rs != cs:
                    flag = f"**CROSSES** ({'excl.' if rs else 'incl.'} {null:g} → {'excl.' if cs else 'incl.'} {null:g})"
        self.lines.append(f"| {label} | {_cell(r, digits)} | {_cell(c, digits)} | {delta} | {flag} |")
        return self

    def __str__(self):
        return "\n".join(self.lines)


def render(comparison: dict, recorded: dict, corrected: dict, stored: dict) -> str:
    rec = {**recorded, "population": stored["population"]}
    T = lambda header="Metric": Table(rec, corrected, header)  # noqa: E731
    out = []
    w = out.append

    crossings = comparison["crossings"]
    repro = comparison["reproduction"]
    n_repro = sum(r["n_values"] for r in repro.values())
    pop_r, pop_c = rec["population"], corrected["population"]

    w("# Results with corrected labels\n")
    w("**This is a new record beside `docs/final_results.md`, not a replacement.** "
      "Generated by `python -m scripts.evaluate.corrected_labels report` "
      "(`scripts/evaluate/corrected_labels_report.py`). Do not edit by hand.\n")
    prov = corrected["provenance"]
    w(f"**Record.** `results/corrected_labels/corrected.json`, generated at commit `{prov['git_commit']}` "
      f"({prov['generated_at_utc']}); the stored pass ran at the same commit. `vsp results` prints this "
      "record for presentation, and `vsp results --check` verifies its output against the record.\n")
    w("**What changed.** The labels of **18 test rows (6 CVEs)** and nothing else. The stored table "
      "`training.training_dataset` was built from KEV catalog 2026.08.06. These 6 CVEs were added to KEV "
      "between that catalog and the test label cutoff (2026-09-20), so their rows change from censored at "
      "the cutoff to events at the listing date. The list is in `tests/fixtures/kev_label_diffs_20261021.json`; "
      "`tests/test_features/test_build_reproduces_training_dataset.py` checks that these are the only label "
      "differences and that no feature differs. The relabel is done in memory "
      "(`scripts/evaluate/label_corrections.py`). `training.training_dataset` is not written to.\n")
    w("**What did not change.** The frozen models, the stored features and the corrected encoding are "
      "the same. So are the seed (20260922) and the 200 whole-CVE resamples, all through "
      "`scripts/evaluate/common.py`. "
      "The only refits are those the recorded analyses already did: the trajectory ablations and the "
      "rolling-origin folds. All 6 listings fall after every training cutoff, so their training labels "
      "are identical. **Not re-run:** the RSF seed-variance study (RSF refits are not reproducible, so a "
      "re-run would confound the label change with run-to-run noise).\n")
    w(f"**Reproduction check (passed).** The same code run on the stored labels reproduces the recorded "
      f"result files **exactly**: {n_repro:,} numbers across {len(repro)} files, 0 mismatches. So "
      f"every difference below is the effect of the 18 relabelled rows alone.\n")
    w("**Notation.** \"Recorded\" is the number in `docs/final_results.md` (unrounded here). Δ = corrected − "
      "recorded, on the point estimate. 95% CIs are in parentheses. A paired difference is **bold** when its "
      "CI excludes zero. \"Boundary\" flags a CI that excluded the null before and does not now, or the "
      "reverse. The null is 0 for differences, 1× for effort ratios and 0.5 for a C-index.\n")

    w("## Significance-boundary crossings\n")
    if crossings:
        w(f"{len(crossings)} of the compared intervals cross their null:\n")
        w("| Analysis | Quantity | Recorded | Corrected |")
        w("|---|---|---|---|")
        for c in crossings:
            rlo, rhi = c["recorded_ci"]
            clo, chi = c["corrected_ci"]
            w(f"| {c['analysis']} | `{c['path']}` | {c['recorded']:+.4f} ({rlo:+.4f}, {rhi:+.4f}) | "
              f"{c['corrected']:+.4f} ({clo:+.4f}, {chi:+.4f}) |")
        w("")
    else:
        w("**None.** Across every compared interval (each paired difference, each budget-equivalence ratio, "
          "IPA, the blind-spot, lead-time and sensitivity estimates, all four rolling-origin folds), no CI "
          "moves across its null.\n")

    # population
    w("## Population\n")
    t = T("Test set")
    t.row("Rows", ("population", "n_rows")).row("CVEs", ("population", "n_cves"))
    t.row("KEV events (rows)", ("population", "n_events")).row("Event CVEs", ("population", "n_event_cves"))
    t.row("Events within 90 days of landmark", ("population", "n_events_within_90d"))
    for lm in LANDMARKS:
        t.row(f"Day {lm}: events", ("population", "per_landmark", lm, "n_events"))
    w(str(t) + "\n")
    diffs = known_diffs()
    lo, hi = diffs["corrected_event_time"].min(), diffs["corrected_event_time"].max()
    w(f"The {len(diffs)} new event rows have event times of {lo}–{hi} days"
      + (". None falls within 90 days, so the 90-day calibration base is unchanged.\n"
         if pop_c["n_events_within_90d"] == pop_r["n_events_within_90d"] else ".\n"))

    H = ("headline",)
    w("## Model comparison\n")
    t = T("Ranking / metric")
    for m in RANKINGS:
        t.row(f"{m} C-index", H + ("metrics", m, "cindex"), null=0.5)
        for b in BUDGETS:
            t.row(f"{m} Recall@{b[:-3]}%", H + ("metrics", m, "recall_at_budget", b))
    for m in MODELS:
        t.row(f"{m} blind-spot catch @10%", H + ("blind_spot_catch_rate_10pct", m), null=0.0)
    w(str(t) + "\n")

    w("### Paired difference vs EPSS-alone (`epss_pct_now`)\n")
    t = T("Model / metric")
    for m in MODELS:
        for k in PAIRED:
            t.row(f"{m} {PAIRED_NAMES[k]}", H + ("paired_vs_epss", m, k))
    t.row("XGBoost-AFT ΔC-index vs raw EPSS", H + ("xgb_cindex_vs_epss", "vs_epss_raw"))
    for m in ("RSF", "XGBoost-AFT"):
        t.row(f"Blind-spot catch, {m} − Cox", H + ("blind_spot_paired_vs_cox", m))
    w(str(t) + "\n")

    w("### Per-landmark C-index\n")
    t = T("Landmark / ranking")
    for lm in LANDMARKS:
        for m in RANKINGS:
            t.row(f"day {lm} {m}", H + ("per_landmark", m, lm, "cindex"), null=0.5)
    w(str(t) + "\n")

    w("## Budget equivalence (Cox vs EPSS-alone)\n")
    t = T("Quantity")
    for b in BUDGETS:
        B = ("budget_equivalence",)
        t.row(f"{b[:-3]}%: Cox recall", B + (f"cox_recall_{b}",))
        t.row(f"{b[:-3]}%: EPSS recall", B + (f"epss_recall_{b}",))
        t.row(f"{b[:-3]}%: EPSS budget to match", B + (f"epss_budget_to_match_{b}",), digits=4)
        t.row(f"{b[:-3]}%: effort ratio (×)", B + (f"effort_ratio_{b}",), digits=2, null=1.0)
    w(str(t) + "\n")

    TD = H + ("time_dependent_auc",)
    w("## Time-dependent AUC (cumulative/dynamic; censoring weights from train)\n")
    t = T("Model / horizon")
    for m in MODELS + ("EPSS raw",):
        for h in HORIZONS:
            t.row(f"{m} AUC {h}d", TD + ("pooled", m, h), null=0.5)
    for m in MODELS:
        for h in HORIZONS:
            t.row(f"{m} ΔAUC {h}d vs raw EPSS", TD + ("paired_vs_epss", "pooled", m, h))
    w(str(t) + "\n")
    w("Per landmark (point AUC with CI; paired Δ vs raw EPSS):\n")
    t = T("Landmark / model / horizon")
    for lm in LANDMARKS:
        for m in MODELS + ("EPSS raw",):
            for h in HORIZONS:
                t.row(f"day {lm} {m} AUC {h}d", TD + ("per_landmark", f"landmark_{lm}", m, h), null=0.5)
        for m in MODELS:
            for h in HORIZONS:
                t.row(f"day {lm} {m} ΔAUC {h}d", TD + ("paired_vs_epss", f"landmark_{lm}", m, h))
    w(str(t) + "\n")
    oor_r, oor_c = _get(rec, TD + ("out_of_range",)), _get(corrected, TD + ("out_of_range",))
    w(f"Out-of-range horizons: recorded {len(oor_r) or 'none'}, corrected {len(oor_c) or 'none'}.\n")

    BR = H + ("cox_brier_calibration", "brier")
    w("## Brier score and IPA (Cox)\n")
    t = T("Metric")
    for h in HORIZONS:
        t.row(f"Brier {h}d", BR + (f"brier_{h}d",), digits=6)
        t.row(f"Brier {h}d, reference (training KM)", BR + (f"brier_{h}d_reference",), digits=6)
        t.row(f"IPA {h}d", BR + (f"ipa_{h}d",), digits=6, null=0.0)
    t.row("Integrated Brier 30–180d", BR + ("ibs",), digits=6)
    t.row("Integrated Brier, reference", BR + ("ibs_reference",), digits=6)
    t.row("IPA (integrated)", BR + ("ipa_ibs",), digits=6, null=0.0)
    w(str(t) + "\n")

    CAL = H + ("cox_brier_calibration", "calibration_90d")
    w("90-day calibration by decile of predicted risk (observed = KM):\n")
    w("| Decile | Mean predicted | Observed, recorded | Observed, corrected | Events by 90d, recorded → corrected |")
    w("|---|---|---|---|---|")
    for r_, c_ in zip(_get(rec, CAL), _get(corrected, CAL)):
        w(f"| {r_['bin']} | {r_['mean_predicted']:.3%} | {r_['observed']:.3%} | {c_['observed']:.3%} | "
          f"{r_['n_events_by_horizon']} → {c_['n_events_by_horizon']} |")
    w("")

    for name, title in (("cox_trajectory_ablation", "Trajectory ablation (H1), Cox"),
                        ("xgb_trajectory_ablation", "Trajectory ablation, XGBoost-AFT")):
        w(f"## {title}\n")
        t = T("Feature set / comparison")
        for fs in ("a) full model", "b) minus trajectory", "c) minus all EPSS"):
            for k, label in (("cindex", "C-index"), ("recall_5pct", "Recall@5%"), ("recall_10pct", "Recall@10%")):
                t.row(f"{fs}: {label}", (name, fs, k), digits=4)
        for pair, label in (("paired_a_minus_b", "(a) − (b)"), ("paired_a_minus_c", "(a) − (c)")):
            for k in PAIRED:
                t.row(f"{label} {PAIRED_NAMES[k]}", (name, pair, k), digits=4 if k == "cindex" else 3)
        w(str(t) + "\n")

    F = ("fuzzy",)
    w("## Fuzzy layer vs Cox / EPSS / linear blend\n")
    t = T("Ranking / metric")
    for m in ("Fuzzy", "Cox", "EPSS", "Linear blend"):
        t.row(f"{m} C-index", F + ("metrics", m, "cindex"), null=0.5)
        for b in BUDGETS:
            t.row(f"{m} Recall@{b[:-3]}%", F + ("metrics", m, "recall_at_budget", b))
    for m in ("Fuzzy", "Cox", "Linear blend"):
        t.row(f"{m} blind-spot catch @10%", F + ("blind_spot_catch_rate_10pct", "per_model", m), null=0.0)
    for ref in ("Cox", "EPSS", "Linear blend"):
        for k in PAIRED:
            t.row(f"Fuzzy − {ref} {PAIRED_NAMES[k]}", F + ("paired_fuzzy_minus_reference", ref, k))
    for ref in ("Cox", "Linear blend"):
        t.row(f"Fuzzy − {ref} ΔBlind-spot @10%", F + ("blind_spot_catch_rate_10pct", f"paired_fuzzy_minus_{ref}"))
    w(str(t) + "\n")

    w("## Rolling-origin consistency check\n")
    published = {c["cve_id"]: pd.Timestamp(c["published_date"]) for c in load_record()["cves"]}
    in_fold = {k: sorted(c for c, d in published.items()
                         if pd.Timestamp(k) <= d < pd.Timestamp(k) + pd.DateOffset(months=6))
               for k in ("2024-01-01", "2024-07-01", "2025-01-01", "2025-07-01")}
    placed = "; ".join(f"{k}: {', '.join(v)}" for k, v in in_fold.items() if v) or "none"
    w("Each fold's Cox is refit on train labels censored at its cutoff (unchanged); test labels are "
      f"observed to 2026-09-20. Relabelled CVEs by fold test window: {placed}. "
      f"{len(published) - sum(map(len, in_fold.values()))} of the {len(published)} were published after the "
      "last window and are in no fold.\n")
    t = T("Fold / quantity")
    for k in ("2024-01-01", "2024-07-01", "2025-01-01", "2025-07-01"):
        RO = ("rolling_origin", k)
        t.row(f"{k}: test events", RO + ("test", "n_events"))
        t.row(f"{k}: Cox C-index", RO + ("Cox", "cindex"), null=0.5)
        t.row(f"{k}: EPSS C-index", RO + ("EPSS-alone", "cindex"), null=0.5)
        for m in PAIRED:
            t.row(f"{k}: Cox − EPSS {PAIRED_NAMES[m]}", RO + ("paired_cox_minus_epss", m))
    w(str(t) + "\n")

    L = ("lead_time", "stats")
    w("## Lead time (post-hoc, descriptive)\n")
    t = T("Measure")
    t.row("Listed test CVEs", ("lead_time", "n_listed_cves"))
    for k, label in (("n_both", "Cox and EPSS catch"), ("n_cox_only", "Cox only"), ("n_epss_only", "EPSS only"),
                     ("n_neither", "neither"), ("blind_n", "Blind spots (EPSS never catches)"),
                     ("blind_cox_caught", "Blind spots Cox recovers")):
        t.row(label, L + (k,), digits=0)
    t.row("Blind-spot recovery rate", L + ("blind_cox_catch_rate",), null=0.0)
    t.row("Cox lead over EPSS, mean (either caught), days", L + ("either_mean",), digits=1, null=0.0)
    t.row("Cox lead over EPSS, median (either caught), days", L + ("either_median",), digits=1)
    t.row("Cox lead over EPSS, median (both caught), days", L + ("both_median",), digits=1)
    t.row("Cox lead before listing on recovered blind spots, median, days", L + ("blind_cox_lead_median",),
          digits=1)
    w(str(t) + "\n")
    dist_r = rec["lead_time"]["lead_days_distribution"]
    dist_c = corrected["lead_time"]["lead_days_distribution"]
    w("| Lead before listing given caught | Recorded median (n) | Corrected median (n) |")
    w("|---|---|---|")
    for m in ("cox", "epss"):
        r_, c_ = dist_r[f"{m}_given_caught"], dist_c[f"{m}_given_caught"]
        w(f"| {m.upper() if m == 'epss' else 'Cox'} | {r_['50%']:.0f} days (n={r_['count']:.0f}) | "
          f"{c_['50%']:.0f} days (n={c_['count']:.0f}) |")
    w("")

    w("## Sensitivity subsets (Cox vs EPSS-alone)\n")
    t = T("Subset / quantity")
    for s, label in (("baseline", "Baseline"), ("a_with_transition_rows", "+ version-transition rows"),
                     ("b_excluding_vulncheck_cna", "− VulnCheck-CNA CVEs"), ("c_cna_cvss_present", "CNA CVSS present only")):
        S = ("sensitivity", s)
        t.row(f"{label}: events", S + ("n_events",))
        t.row(f"{label}: Cox C-index", S + ("Cox", "cindex"), null=0.5)
        for m in PAIRED:
            t.row(f"{label}: {PAIRED_NAMES[m]} vs EPSS", S + ("paired_cox_minus_epss", m))
        t.row(f"{label}: Cox blind-spot catch @10%", S + ("cox_blind_spot_catch_10pct",), null=0.0)
    w(str(t) + "\n")

    D = ("display_calibration",)
    w("## Display calibration (evaluated and rejected; recalibrators fit on validation, unchanged)\n")
    t = T("Map / metric")
    for m in ("raw", "isotonic", "platt"):
        t.row(f"{m}: Brier 90d", D + ("test_brier_90d", m, "brier"), digits=6)
        t.row(f"{m}: IPA 90d", D + ("test_brier_90d", m, "ipa"), digits=4, null=0.0)
    w(str(t) + "\n")

    w("## Reproduction check detail\n")
    w("| Recorded file (analysis) | Numbers compared | Mismatches |")
    w("|---|---|---|")
    for name, r in repro.items():
        w(f"| {name} | {r['n_values']:,} | {r['mismatches']} |")
    w("")
    return "\n".join(out) + "\n"

